#!/usr/bin/env python3
"""Populate the `location` table from the GeoNames cities dataset.

gitjobs resolves locations by full-text search against its own `location`
table, not by calling a geocoding service, and the table ships empty. Until it
is populated the location field on job seeker profiles and job postings can
never suggest anything, and the distance filter on job search has nothing to
measure against. Nothing upstream seeds it.

This emits SQL on stdout. Pipe it at a database:

    # local dev
    python3 dronecode-locations/load_locations.py | \\
        docker exec -i gjdev psql -U postgres -d gitjobs

    # RDS
    python3 dronecode-locations/load_locations.py | psql "$DATABASE_URL"

The load is idempotent: it stages into a temporary table and replaces the
contents of `location` in one transaction, so re-running refreshes the data
rather than duplicating it.

Source: GeoNames cities15000 (all cities over 15,000 people, ~34k rows),
licensed CC BY 4.0. The full GeoNames dump is millions of rows and mostly
hamlets, which would bloat the typeahead index for no benefit on a job board.
"""

import io
import os
import sys
import urllib.request
import zipfile

BASE = "https://download.geonames.org/export/dump/"
CACHE = os.path.join(os.path.dirname(os.path.abspath(__file__)), ".cache")

# Column positions in the cities15000 export.
C_NAME = 1
C_LAT = 4
C_LON = 5
C_COUNTRY = 8
C_ADMIN1 = 10
C_POPULATION = 14


def fetch(name):
    """Download a GeoNames file, caching it so reruns are offline."""
    os.makedirs(CACHE, exist_ok=True)
    path = os.path.join(CACHE, name)
    if os.path.exists(path):
        return open(path, "rb").read()
    sys.stderr.write("downloading {}\n".format(name))
    with urllib.request.urlopen(BASE + name, timeout=120) as r:
        data = r.read()
    with open(path, "wb") as f:
        f.write(data)
    return data


def country_names():
    """ISO2 country code -> country name."""
    out = {}
    for line in fetch("countryInfo.txt").decode("utf-8").splitlines():
        if line.startswith("#") or not line.strip():
            continue
        parts = line.split("\t")
        if len(parts) > 4:
            out[parts[0]] = parts[4]
    return out


def admin1_names():
    """'<country>.<admin1 code>' -> region name, e.g. 'US.CA' -> 'California'."""
    out = {}
    for line in fetch("admin1CodesASCII.txt").decode("utf-8").splitlines():
        parts = line.split("\t")
        if len(parts) > 1:
            out[parts[0]] = parts[1]
    return out


def cities():
    raw = fetch("cities15000.zip")
    with zipfile.ZipFile(io.BytesIO(raw)) as z:
        return z.read("cities15000.txt").decode("utf-8").splitlines()


def copy_escape(value):
    """Escape a field for COPY ... FROM STDIN in text format."""
    if value is None or value == "":
        return r"\N"
    return (
        value.replace("\\", "\\\\")
        .replace("\t", "\\t")
        .replace("\n", "\\n")
        .replace("\r", "\\r")
    )


def main():
    countries = country_names()
    admin1 = admin1_names()

    rows, skipped = [], 0
    for line in cities():
        f = line.split("\t")
        if len(f) <= C_POPULATION:
            continue
        country = countries.get(f[C_COUNTRY])
        if not country:
            # A city whose country we cannot name would show up in the
            # typeahead as a bare city with no context, so drop it.
            skipped += 1
            continue
        state = admin1.get("{}.{}".format(f[C_COUNTRY], f[C_ADMIN1]))
        rows.append((f[C_NAME], country, state, f[C_LON], f[C_LAT]))

    sys.stderr.write("prepared {} cities ({} skipped)\n".format(len(rows), skipped))

    w = sys.stdout.write
    w("-- Generated by dronecode-locations/load_locations.py\n")
    w("-- Source: GeoNames cities15000, CC BY 4.0\n")
    w("begin;\n\n")
    w("create temporary table location_import (\n")
    w("    city text, country text, state text, lon double precision, lat double precision\n")
    w(") on commit drop;\n\n")
    w("copy location_import (city, country, state, lon, lat) from stdin;\n")
    for city, country, state, lon, lat in rows:
        w("\t".join([
            copy_escape(city), copy_escape(country), copy_escape(state), lon, lat
        ]) + "\n")
    w("\\.\n\n")

    # Replace wholesale rather than upsert. location has no natural key, and
    # job/profile rows reference it by location_id, so deleting rows that are
    # still referenced must fail loudly rather than cascade.
    w("delete from location;\n\n")
    w("insert into location (location_id, city, country, state, coordinates)\n")
    w("select\n")
    w("    gen_random_uuid(),\n")
    w("    city,\n")
    w("    country,\n")
    w("    state,\n")
    w("    st_setsrid(st_makepoint(lon, lat), 4326)::geography\n")
    w("from location_import;\n\n")
    w("commit;\n")
    w("select count(*) as locations_loaded from location;\n")


if __name__ == "__main__":
    main()
